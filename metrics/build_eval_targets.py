"""Rebuild the canonical CAMELS-US MIP observed streamflow targets from raw NCAR CAMELS-US files.

This module is the single reproducible source of the ground-truth store
`observations/newman_eval_targets.zarr` (published at
`gs://camels-us-mip/observations/newman_eval_targets.zarr`).
Given a local copy of the standard NCAR CAMELS-US v1.2 directory tree and the canonical split
files shipped in this repository (`mips/camels_us_daily/splits/basins_531.json` and
`mips/camels_us_daily/splits/splits_and_regimes.json`),
it deterministically rebuilds the store from scratch, so the evaluation targets can be audited and
regenerated by anyone from repository code alone.

Raw inputs (standard NCAR CAMELS-US v1.2 layout below `--camels-dir`):

* `usgs_streamflow/<HUC02>/<basin>_streamflow_qc.txt`: whitespace-separated daily USGS discharge
  with columns `gauge_id year month day q_cfs flag`. The sentinel `-999` (and any negative value)
  marks missing data and becomes `NaN` (never `0`).
* `basin_mean_forcing/daymet/<HUC02>/<basin>_lump_cida_forcing_leap.txt`: the third header line
  holds the catchment area in square metres used to convert discharge to specific discharge.

Unit conversion: `mm/day = q_cfs * 0.028316846592 * 86400 * 1000 / area_m2`, where
`0.028316846592 = 0.3048 ** 3` is the exact volume of one cubic foot in cubic metres (international
foot). With this constant the rebuild reproduces the canonical store bit-for-bit in float32; the
truncated `0.0283168` would differ by up to ~7e-4 mm/day.

Output schema (identical to the canonical store):

* dims `basin` (531), `date` (3652 days, 1989-10-01 to 1999-09-30) and `date_all` (10593 days,
  1980-01-01 to 2008-12-31);
* coords `basin` (`<U8`, sorted 8-digit USGS gauge IDs), `date` and `date_all`
  (`datetime64[ns]`) and `huc_02` (`<U2`, the two-digit region directory each basin file sits in,
  cross-checked against `splits_and_regimes.json["basin_to_huc02"]`);
* data variables `qobs` (`basin`, `date`, float32 mm/day), `qobs_all` (`basin`, `date_all`,
  float32 mm/day), `newman_test_mask` and `newman_train_mask` (`date_all`, bool).

Command line usage:

    python -m metrics.build_eval_targets \\
        --camels-dir /path/to/basin_dataset_public_v1p2 \\
        --splits-dir mips/camels_us_daily/splits \\
        --output /path/or/gs://uri/newman_eval_targets.zarr \\
        [--verify-against gs://camels-us-mip/observations/newman_eval_targets.zarr]

`--verify-against` compares the freshly rebuilt dataset with an existing store *before* anything
is written and raises (non-zero exit status) unless every coordinate is identical and `qobs`
(and `qobs_all`, when present) agree to within `--atol` (default `1e-3` mm/day) with an identical
missing-data pattern.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Mapping, Sequence
from pathlib import Path

import numpy as np
import pandas as pd
import xarray as xr

from hydromip.evaluation.zarr_io import deterministic_io, get_gcs_storage_options, open_zarr_store
from metrics.evaluator import DEFAULT_BUCKET_URI

# --- Newman et al. (2017) / Kratzert et al. (2019) 531-basin protocol periods --------------------
FULL_PERIOD_START: str = "1980-01-01"
FULL_PERIOD_END: str = "2008-12-31"
TEST_PERIOD_START: str = "1989-10-01"
TEST_PERIOD_END: str = "1999-09-30"
TRAIN_PERIOD_START: str = "1999-10-01"
TRAIN_PERIOD_END: str = "2008-09-30"

# --- Unit conversion constants (cubic feet per second -> millimetres per day) --------------------
# One international foot is exactly 0.3048 m, so one cubic foot is exactly 0.028316846592 m^3.
CUBIC_FEET_TO_CUBIC_METRES: float = 0.028316846592
SECONDS_PER_DAY: int = 86400
MILLIMETRES_PER_METRE: int = 1000
MISSING_STREAMFLOW_SENTINEL: float = -999.0

# --- Standard NCAR CAMELS-US v1.2 directory layout ----------------------------------------------
STREAMFLOW_SUBDIR: str = "usgs_streamflow"
FORCING_SUBDIR: str = "basin_mean_forcing/daymet"
STREAMFLOW_SUFFIX: str = "_streamflow_qc.txt"
FORCING_SUFFIX: str = "_lump_cida_forcing_leap.txt"
STREAMFLOW_COLUMNS: tuple[str, ...] = ("gauge_id", "year", "month", "day", "q_cfs", "flag")
AREA_HEADER_LINE_NUMBER: int = 3

# --- Repository split files -------------------------------------------------------------------
BASINS_FILENAME: str = "basins_531.json"
SPLITS_AND_REGIMES_FILENAME: str = "splits_and_regimes.json"

# --- Canonical output store -------------------------------------------------------------------
CANONICAL_TARGETS_URI: str = f"{DEFAULT_BUCKET_URI}/observations/newman_eval_targets.zarr"
DATASET_TITLE: str = (
    "CAMELS-US MIP Canonical Observed Streamflow Targets (Newman et al. 2017 531-Basin Protocol)"
)
VERIFY_ATOL: float = 1e-3


def full_daily_index() -> pd.DatetimeIndex:
    """Return the 10,593 daily timestamps spanning 1980-01-01 to 2008-12-31 (inclusive)."""
    return pd.date_range(FULL_PERIOD_START, FULL_PERIOD_END, freq="D", name="date_all")


def period_mask(index: pd.DatetimeIndex, start: str, end: str) -> np.ndarray:
    """Return a boolean mask selecting the inclusive `start`..`end` window of `index`."""
    return np.asarray((index >= pd.Timestamp(start)) & (index <= pd.Timestamp(end)), dtype=bool)


def cfs_to_mm_per_day(
    q_cfs: float | np.ndarray,
    area_m2: float,
) -> float | np.ndarray:
    """Convert discharge in cubic feet per second to catchment-area-normalized mm/day."""
    if not np.isfinite(area_m2) or area_m2 <= 0.0:
        raise ValueError(
            f"Catchment area must be a finite positive number of m^2, got {area_m2!r}."
        )
    return q_cfs * CUBIC_FEET_TO_CUBIC_METRES * SECONDS_PER_DAY * MILLIMETRES_PER_METRE / area_m2


def _validate_basin_ids(basins: Sequence[str]) -> list[str]:
    """Return the sorted list of unique 8-digit USGS gauge IDs, raising on malformed input."""
    normalized = [str(b) for b in basins]
    if not normalized:
        raise ValueError("The basin list is empty.")
    malformed = [b for b in normalized if len(b) != 8 or not b.isdigit()]
    if malformed:
        raise ValueError(f"Basin IDs must be 8-digit USGS gauge IDs, got malformed: {malformed}.")
    if len(set(normalized)) != len(normalized):
        duplicates = sorted({b for b in normalized if normalized.count(b) > 1})
        raise ValueError(f"Basin list contains duplicate IDs: {duplicates}.")
    return sorted(normalized)


def load_canonical_basins(splits_dir: Path) -> list[str]:
    """Load the sorted canonical basin list from `<splits_dir>/basins_531.json`."""
    basins_path = Path(splits_dir) / BASINS_FILENAME
    if not basins_path.is_file():
        raise FileNotFoundError(f"Canonical basin list not found: {basins_path}")
    raw = json.loads(basins_path.read_text(encoding="utf-8"))
    if not isinstance(raw, list):
        raise ValueError(f"{basins_path} must contain a JSON list of basin IDs.")
    return _validate_basin_ids(raw)


def load_splits_and_regimes(splits_dir: Path) -> dict:
    """Load `<splits_dir>/splits_and_regimes.json` and validate its `basin_to_huc02` map."""
    spec_path = Path(splits_dir) / SPLITS_AND_REGIMES_FILENAME
    if not spec_path.is_file():
        raise FileNotFoundError(f"Split specification not found: {spec_path}")
    spec = json.loads(spec_path.read_text(encoding="utf-8"))
    if not isinstance(spec, dict) or "basin_to_huc02" not in spec:
        raise ValueError(f"{spec_path} must be a JSON object with a 'basin_to_huc02' map.")
    basin_to_huc02 = spec["basin_to_huc02"]
    if not isinstance(basin_to_huc02, dict):
        raise ValueError(f"'basin_to_huc02' in {spec_path} must be a JSON object.")
    bad = {b: h for b, h in basin_to_huc02.items() if len(str(h)) != 2 or not str(h).isdigit()}
    if bad:
        raise ValueError(f"'basin_to_huc02' in {spec_path} has non-2-digit HUC codes: {bad}.")
    _validate_basin_ids(list(basin_to_huc02))
    return spec


def index_basin_files(root: Path, suffix: str) -> dict[str, Path]:
    """Map basin ID -> file path for every `<root>/<HUC02>/<basin><suffix>` file.

    Raises `FileNotFoundError` if `root` is not a directory and `ValueError` if the same basin
    appears below more than one region directory (its HUC-02 would be ambiguous).
    """
    root = Path(root)
    if not root.is_dir():
        raise FileNotFoundError(f"CAMELS directory not found: {root}")
    index: dict[str, Path] = {}
    for path in sorted(root.glob(f"*/*{suffix}")):
        if not path.is_file():
            continue
        basin = path.name[: -len(suffix)]
        if basin in index:
            raise ValueError(
                f"Basin {basin} appears under more than one HUC-02 directory: "
                f"{index[basin]} and {path}."
            )
        index[basin] = path
    return index


def read_basin_area_m2(forcing_path: Path) -> float:
    """Read the catchment area (m^2) from the third header line of a Daymet forcing file."""
    forcing_path = Path(forcing_path)
    if not forcing_path.is_file():
        raise FileNotFoundError(f"Forcing file not found: {forcing_path}")
    with forcing_path.open("r", encoding="utf-8") as handle:
        header_lines = [handle.readline() for _ in range(AREA_HEADER_LINE_NUMBER)]
    area_text = header_lines[AREA_HEADER_LINE_NUMBER - 1].strip()
    if not area_text:
        raise ValueError(
            f"Header line {AREA_HEADER_LINE_NUMBER} of {forcing_path} (catchment area in m^2) "
            "is empty or missing."
        )
    area_m2 = float(area_text)
    if not np.isfinite(area_m2) or area_m2 <= 0.0:
        raise ValueError(f"Catchment area in {forcing_path} must be positive, got {area_m2!r}.")
    return area_m2


def read_streamflow_cfs(streamflow_path: Path, basin: str) -> pd.Series:
    """Read a raw `<basin>_streamflow_qc.txt` file into a daily series of discharge in cfs.

    The series is indexed by calendar date exactly as recorded in the file (no reindexing).
    Missing values (`-999` and any other negative discharge) are returned as `NaN`.
    """
    streamflow_path = Path(streamflow_path)
    if not streamflow_path.is_file():
        raise FileNotFoundError(f"Streamflow file not found: {streamflow_path}")
    frame = pd.read_csv(
        streamflow_path,
        sep=r"\s+",
        header=None,
        names=list(STREAMFLOW_COLUMNS),
        dtype={"gauge_id": str, "flag": str},
    )
    if frame.empty:
        raise ValueError(f"Streamflow file {streamflow_path} contains no data rows.")
    foreign_ids = sorted(set(frame["gauge_id"]) - {basin})
    if foreign_ids:
        raise ValueError(
            f"Streamflow file {streamflow_path} contains gauge IDs {foreign_ids} that differ "
            f"from the expected basin {basin}."
        )
    if frame[["year", "month", "day", "q_cfs"]].isna().any().any():
        raise ValueError(f"Streamflow file {streamflow_path} has unparsable date or discharge.")
    dates = pd.DatetimeIndex(pd.to_datetime(frame[["year", "month", "day"]]))
    if dates.has_duplicates:
        duplicated = sorted(set(dates[dates.duplicated()].strftime("%Y-%m-%d")))
        raise ValueError(f"Streamflow file {streamflow_path} has duplicate dates: {duplicated}.")
    q_cfs = frame["q_cfs"].to_numpy(dtype=np.float64, copy=True)
    q_cfs[q_cfs < 0.0] = np.nan
    return pd.Series(q_cfs, index=dates, name="q_cfs")


def build_eval_targets(
    camels_dir: Path,
    splits_dir: Path,
    basins: Sequence[str] | None = None,
) -> xr.Dataset:
    """Build the canonical observed-streamflow targets dataset from raw CAMELS-US files.

    Args:
        camels_dir: Root of the NCAR CAMELS-US v1.2 tree (contains `usgs_streamflow/` and
            `basin_mean_forcing/daymet/`).
        splits_dir: Directory holding `basins_531.json` and `splits_and_regimes.json`.
        basins: Optional explicit basin list overriding `basins_531.json` (used by tests). Every
            basin must still be present in `splits_and_regimes.json["basin_to_huc02"]`.

    Returns:
        An in-memory `xarray.Dataset` with the canonical `newman_eval_targets.zarr` schema.

    Raises:
        FileNotFoundError: A required directory or per-basin file is missing (nothing is skipped).
        ValueError: Split files are inconsistent, a basin sits in a HUC-02 directory that does
            not match `basin_to_huc02`, or a raw file is malformed.
    """
    camels_dir = Path(camels_dir)
    splits_dir = Path(splits_dir)
    spec = load_splits_and_regimes(splits_dir)
    basin_to_huc02: Mapping[str, str] = {str(b): str(h) for b, h in spec["basin_to_huc02"].items()}

    if basins is None:
        basin_list = load_canonical_basins(splits_dir)
        if set(basin_list) != set(basin_to_huc02):
            raise ValueError(
                f"{BASINS_FILENAME} and {SPLITS_AND_REGIMES_FILENAME}['basin_to_huc02'] "
                "do not describe the same basin set."
            )
        if "num_basins" in spec and int(spec["num_basins"]) != len(basin_list):
            raise ValueError(
                f"{SPLITS_AND_REGIMES_FILENAME} declares num_basins={spec['num_basins']} but "
                f"{BASINS_FILENAME} lists {len(basin_list)} basins."
            )
    else:
        basin_list = _validate_basin_ids(basins)
        unknown = [b for b in basin_list if b not in basin_to_huc02]
        if unknown:
            raise ValueError(
                f"Basins {unknown} are not present in "
                f"{SPLITS_AND_REGIMES_FILENAME}['basin_to_huc02']."
            )

    streamflow_files = index_basin_files(camels_dir / STREAMFLOW_SUBDIR, STREAMFLOW_SUFFIX)
    forcing_files = index_basin_files(camels_dir / FORCING_SUBDIR, FORCING_SUFFIX)

    date_all = full_daily_index()
    qobs_all = np.full((len(basin_list), len(date_all)), np.nan, dtype=np.float64)
    huc_02 = np.empty(len(basin_list), dtype="<U2")

    for i, basin in enumerate(basin_list):
        if basin not in streamflow_files:
            raise FileNotFoundError(
                f"Missing streamflow file for basin {basin}: expected "
                f"{camels_dir / STREAMFLOW_SUBDIR}/<HUC02>/{basin}{STREAMFLOW_SUFFIX}"
            )
        if basin not in forcing_files:
            raise FileNotFoundError(
                f"Missing Daymet forcing file for basin {basin}: expected "
                f"{camels_dir / FORCING_SUBDIR}/<HUC02>/{basin}{FORCING_SUFFIX}"
            )
        streamflow_path = streamflow_files[basin]
        forcing_path = forcing_files[basin]
        huc_from_dir = streamflow_path.parent.name
        if forcing_path.parent.name != huc_from_dir:
            raise ValueError(
                f"Basin {basin}: streamflow file sits in HUC-02 directory '{huc_from_dir}' but "
                f"forcing file sits in '{forcing_path.parent.name}'."
            )
        expected_huc = basin_to_huc02[basin]
        if huc_from_dir != expected_huc:
            raise ValueError(
                f"Basin {basin}: HUC-02 directory '{huc_from_dir}' does not match "
                f"{SPLITS_AND_REGIMES_FILENAME}['basin_to_huc02'] = '{expected_huc}'."
            )
        area_m2 = read_basin_area_m2(forcing_path)
        q_cfs = read_streamflow_cfs(streamflow_path, basin).reindex(date_all)
        qobs_all[i, :] = cfs_to_mm_per_day(q_cfs.to_numpy(dtype=np.float64), area_m2)
        huc_02[i] = huc_from_dir

    test_mask = period_mask(date_all, TEST_PERIOD_START, TEST_PERIOD_END)
    train_mask = period_mask(date_all, TRAIN_PERIOD_START, TRAIN_PERIOD_END)
    date = date_all[test_mask].rename("date")
    qobs_all_f32 = qobs_all.astype(np.float32)
    qobs_f32 = qobs_all_f32[:, test_mask]

    return xr.Dataset(
        data_vars={
            "qobs": (
                ("basin", "date"),
                qobs_f32,
                {
                    "units": "mm/day",
                    "long_name": (
                        "Observed catchment-area-normalized daily specific discharge on the "
                        f"Newman evaluation decade ({TEST_PERIOD_START} to {TEST_PERIOD_END})"
                    ),
                },
            ),
            "qobs_all": (
                ("basin", "date_all"),
                qobs_all_f32,
                {
                    "units": "mm/day",
                    "long_name": (
                        "Observed catchment-area-normalized daily specific discharge across the "
                        "full 1980-2008 record"
                    ),
                },
            ),
            "newman_test_mask": (
                ("date_all",),
                test_mask,
                {
                    "long_name": (
                        "Boolean mask for the 10-water-year Newman evaluation period "
                        f"({TEST_PERIOD_START} to {TEST_PERIOD_END}, {int(test_mask.sum())} days)"
                    )
                },
            ),
            "newman_train_mask": (
                ("date_all",),
                train_mask,
                {
                    "long_name": (
                        "Boolean mask for the 9-water-year Newman training period "
                        f"({TRAIN_PERIOD_START} to {TRAIN_PERIOD_END}, "
                        f"{int(train_mask.sum())} days)"
                    )
                },
            ),
        },
        coords={
            "basin": (
                "basin",
                np.asarray(basin_list, dtype="<U8"),
                {"long_name": f"Sorted canonical {len(basin_list)} USGS 8-digit gauge ID"},
            ),
            "date": (
                "date",
                date.values.astype("datetime64[ns]"),
                {"long_name": f"Daily evaluation date ({TEST_PERIOD_START} to {TEST_PERIOD_END})"},
            ),
            "date_all": (
                "date_all",
                date_all.values.astype("datetime64[ns]"),
                {
                    "long_name": (
                        f"Daily date across full record ({FULL_PERIOD_START} to {FULL_PERIOD_END})"
                    )
                },
            ),
            "huc_02": (
                "basin",
                huc_02,
                {"long_name": "Two-digit USGS hydrologic region (01 to 18)"},
            ),
        },
        attrs={
            "title": DATASET_TITLE,
            "num_basins": len(basin_list),
            "train_period": f"{TRAIN_PERIOD_START}/{TRAIN_PERIOD_END}",
            "test_period": f"{TEST_PERIOD_START}/{TEST_PERIOD_END}",
            "full_period": f"{FULL_PERIOD_START}/{FULL_PERIOD_END}",
            "units": "mm/day",
        },
    )


def _coordinate_values(ds: xr.Dataset, name: str) -> np.ndarray:
    """Return a coordinate as a comparable numpy array (`datetime64[ns]` or `str`)."""
    values = np.asarray(ds[name].values)
    if np.issubdtype(values.dtype, np.datetime64):
        return values.astype("datetime64[ns]")
    return values.astype(str)


def verify_against_existing(
    built: xr.Dataset,
    existing: xr.Dataset,
    atol: float = VERIFY_ATOL,
) -> dict[str, float]:
    """Assert that a rebuilt dataset reproduces an existing targets store.

    Every coordinate (`basin`, `date`, `date_all`, `huc_02`) must be identical, the boolean
    period masks must be identical when present, and `qobs` (plus `qobs_all` when present) must
    have an identical `NaN` pattern and agree to within `atol` mm/day everywhere else.

    Returns:
        Mapping of verified data variable name -> maximum absolute difference (mm/day).

    Raises:
        ValueError: Any coordinate, mask, missing-data pattern or value mismatch.
    """
    for name in ("basin", "date", "date_all", "huc_02"):
        if name not in existing.variables:
            raise ValueError(f"Existing store has no '{name}' coordinate.")
        built_values = _coordinate_values(built, name)
        existing_values = _coordinate_values(existing, name)
        if built_values.shape != existing_values.shape:
            raise ValueError(
                f"Coordinate '{name}' shape mismatch: rebuilt {built_values.shape} vs existing "
                f"{existing_values.shape}."
            )
        if not np.array_equal(built_values, existing_values):
            first = int(np.flatnonzero(built_values != existing_values)[0])
            raise ValueError(
                f"Coordinate '{name}' mismatch at index {first}: rebuilt "
                f"{built_values[first]!r} vs existing {existing_values[first]!r}."
            )

    for name in ("newman_test_mask", "newman_train_mask"):
        if name in existing.variables and not np.array_equal(
            np.asarray(built[name].values, dtype=bool),
            np.asarray(existing[name].values, dtype=bool),
        ):
            raise ValueError(f"Boolean mask '{name}' differs from the existing store.")

    if "qobs" not in existing.variables:
        raise ValueError("Existing store has no 'qobs' variable.")
    max_abs_diffs: dict[str, float] = {}
    for name in ("qobs", "qobs_all"):
        if name not in existing.variables:
            continue
        built_values = np.asarray(built[name].values, dtype=np.float64)
        existing_values = np.asarray(existing[name].values, dtype=np.float64)
        if built_values.shape != existing_values.shape:
            raise ValueError(
                f"'{name}' shape mismatch: rebuilt {built_values.shape} vs existing "
                f"{existing_values.shape}."
            )
        built_nan = np.isnan(built_values)
        existing_nan = np.isnan(existing_values)
        if not np.array_equal(built_nan, existing_nan):
            raise ValueError(
                f"'{name}' missing-data pattern differs: {int(np.sum(built_nan != existing_nan))} "
                f"cells are NaN in only one of the two stores (rebuilt has {int(built_nan.sum())} "
                f"NaN, existing has {int(existing_nan.sum())} NaN)."
            )
        valid = ~built_nan
        max_abs = 0.0
        if valid.any():
            max_abs = float(np.max(np.abs(built_values[valid] - existing_values[valid])))
        if max_abs > atol:
            raise ValueError(
                f"'{name}' values differ from the existing store: max |rebuilt - existing| = "
                f"{max_abs:.6g} mm/day exceeds atol={atol:g}."
            )
        max_abs_diffs[name] = max_abs
    return max_abs_diffs


def write_eval_targets_zarr(ds: xr.Dataset, output: str) -> str:
    """Write the targets dataset as a consolidated Zarr v2 store to a local path or `gs://` URI."""
    n_basins = ds.sizes["basin"]
    n_dates = ds.sizes["date"]
    n_dates_all = ds.sizes["date_all"]
    encoding: dict[str, dict[str, object]] = {
        "qobs": {"chunks": (n_basins, n_dates), "dtype": "float32", "_FillValue": np.nan},
        "qobs_all": {"chunks": (n_basins, n_dates_all), "dtype": "float32", "_FillValue": np.nan},
        "newman_test_mask": {"chunks": (n_dates_all,), "dtype": "bool"},
        "newman_train_mask": {"chunks": (n_dates_all,), "dtype": "bool"},
        "basin": {"chunks": (n_basins,), "dtype": "<U8"},
        "huc_02": {"chunks": (n_basins,), "dtype": "<U2"},
        "date": {
            "chunks": (n_dates,),
            "dtype": "int64",
            "units": f"days since {TEST_PERIOD_START} 00:00:00",
            "calendar": "proleptic_gregorian",
        },
        "date_all": {
            "chunks": (n_dates_all,),
            "dtype": "int64",
            "units": f"days since {FULL_PERIOD_START} 00:00:00",
            "calendar": "proleptic_gregorian",
        },
    }
    if output.startswith("gs://"):
        ds.to_zarr(
            output,
            mode="w",
            consolidated=True,
            zarr_format=2,
            encoding=encoding,
            storage_options=get_gcs_storage_options(),
        )
        return output
    local_path = Path(output.removeprefix("file://"))
    local_path.parent.mkdir(parents=True, exist_ok=True)
    ds.to_zarr(str(local_path), mode="w", consolidated=True, zarr_format=2, encoding=encoding)
    return str(local_path)


def build_arg_parser() -> argparse.ArgumentParser:
    """Create the command line parser for `python -m metrics.build_eval_targets`."""
    parser = argparse.ArgumentParser(
        prog="python -m metrics.build_eval_targets",
        description=(
            "Deterministically rebuild observations/newman_eval_targets.zarr from raw NCAR "
            "CAMELS-US v1.2 files and the repository split files."
        ),
    )
    parser.add_argument(
        "--camels-dir",
        type=Path,
        required=True,
        help="Root of the NCAR CAMELS-US v1.2 tree (basin_dataset_public_v1p2).",
    )
    parser.add_argument(
        "--splits-dir",
        type=Path,
        required=True,
        help="Directory containing basins_531.json and splits_and_regimes.json.",
    )
    parser.add_argument(
        "--output",
        type=str,
        required=True,
        help="Destination Zarr store: local path or gs:// URI (overwritten).",
    )
    parser.add_argument(
        "--verify-against",
        type=str,
        default=None,
        help=(
            "Existing targets Zarr store (local path or gs:// URI) that the rebuild must "
            "reproduce; checked before writing --output, non-zero exit status on mismatch."
        ),
    )
    parser.add_argument(
        "--atol",
        type=float,
        default=VERIFY_ATOL,
        help=f"Absolute tolerance in mm/day for --verify-against (default {VERIFY_ATOL:g}).",
    )
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    """Rebuild, optionally verify, and write the canonical targets store. Returns exit status."""
    args = build_arg_parser().parse_args(argv)

    ds = build_eval_targets(args.camels_dir, args.splits_dir)
    n_nan_eval = int(np.isnan(ds["qobs"].values).sum())
    print(
        f"Rebuilt targets for {ds.sizes['basin']} basins: qobs {ds['qobs'].shape}, "
        f"qobs_all {ds['qobs_all'].shape}, {n_nan_eval} NaN cells in the evaluation period.",
        flush=True,
    )

    if args.verify_against is not None:
        with deterministic_io():
            existing = open_zarr_store(args.verify_against)
            max_abs_diffs = verify_against_existing(ds, existing, atol=args.atol)
        for name, max_abs in max_abs_diffs.items():
            print(
                f"Verified '{name}' against {args.verify_against}: identical coordinates and "
                f"NaN pattern, max |rebuilt - existing| = {max_abs:.6g} mm/day "
                f"(atol={args.atol:g}).",
                flush=True,
            )

    written = write_eval_targets_zarr(ds, args.output)
    print(f"Wrote consolidated Zarr v2 store to {written}", flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
